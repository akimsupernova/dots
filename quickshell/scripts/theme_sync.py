#!/usr/bin/env python3
"""Sync the wallpaper accent to kitty, fish prompt, GTK 3/4, qt5ct/qt6ct and Kvantum.

Usage:
  theme_sync.py --accent #rrggbb [--mode dark|light]
  theme_sync.py --from-state          (accent.json written by extract_accent.py)
  theme_sync.py --default             (shell default accent)

Env:
  GLASSVEIL_THEME_MODE   dark | light   (default: dark)
  XDG_CONFIG_HOME        output root for testing
"""
import colorsys
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HOME = Path.home()
CFG = Path(os.environ.get("XDG_CONFIG_HOME") or HOME / ".config")
STATE = Path(os.environ.get("XDG_STATE_HOME") or HOME / ".local" / "state") / "quickshell" / "accent.json"
DEFAULT_ACCENT = "#33ccff"
HEADER = "generated by Glassveil theme_sync.py - do not edit, it is rewritten on every wallpaper change"

KV_DARK = ["KvLibadwaitaDark", "KvFlat", "KvAdaptaDark", "KvArcDark", "KvDark"]
KV_LIGHT = ["KvLibadwaita", "KvFlatLight", "KvAdapta", "KvArc"]
KV_SEARCH = [HOME / ".local/share/Kvantum", Path("/usr/share/Kvantum")]


def parse(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def hexc(c):
    return "#{:02x}{:02x}{:02x}".format(*(max(0, min(255, round(v * 255))) for v in c))


def hsl(h, s, l):
    return colorsys.hls_to_rgb(h % 1.0, max(0.0, min(1.0, l)), max(0.0, min(1.0, s)))


def to_hsl(c):
    h, l, s = colorsys.rgb_to_hls(*c)
    return h, s, l


def mix(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


def lum(c):
    def lin(v):
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    return 0.2126 * lin(c[0]) + 0.7152 * lin(c[1]) + 0.0722 * lin(c[2])


def contrast(a, b):
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def push(c, against, target, toward):
    """Move c toward `toward` (black/white) until contrast with `against` >= target."""
    for i in range(24):
        if contrast(c, against) >= target:
            break
        c = mix(c, toward, 0.06)
    return c


BLACK, WHITE = (0.0, 0.0, 0.0), (1.0, 1.0, 1.0)


def make_palette(accent_hex, mode):
    acc = parse(accent_hex)
    h, s, l = to_hsl(acc)
    ns = min(0.20, max(0.06, s * 0.28))
    dark = mode == "dark"

    if dark:
        bg, base, alt = hsl(h, ns, .105), hsl(h, ns, .080), hsl(h, ns, .130)
        surface, button = hsl(h, ns, .145), hsl(h, ns, .180)
        border = hsl(h, ns * .8, .270)
        fg = hsl(h, ns * .6, .930)
        dim = push(hsl(h, ns * .5, .66), bg, 4.5, WHITE)
        disabled = hsl(h, ns * .4, .46)
        accent = push(acc, bg, 3.0, WHITE)
        link = push(accent, bg, 4.5, WHITE)
    else:
        bg, base, alt = hsl(h, ns * 1.2, .950), hsl(h, ns, .985), hsl(h, ns, .925)
        surface, button = hsl(h, ns, .970), hsl(h, ns, .900)
        border = hsl(h, ns, .780)
        fg = hsl(h, ns * .8, .100)
        dim = push(hsl(h, ns, .36), bg, 4.5, BLACK)
        disabled = hsl(h, ns, .60)
        accent = push(acc, WHITE, 4.5, BLACK)
        link = push(accent, base, 4.5, BLACK)

    on_accent = (0.063, 0.071, 0.086) if contrast(accent, (0.063, 0.071, 0.086)) >= contrast(accent, WHITE) else WHITE
    warn, ok = parse("#ff5c6c"), parse("#5be38a")
    if not dark:
        warn, ok = parse("#c4223a"), parse("#1f7a45")

    if dark:
        ansi_n = ["#ff6b7d", "#6ee79a", "#f5d070", "#74b4ff", "#d49bff", "#6fe3e8"]
        ansi_b = ["#ff8f9c", "#92f0b5", "#f9e096", "#9bc9ff", "#e3b8ff", "#95eef1"]
        c0, c8, c7, c15 = mix(bg, fg, .14), mix(bg, fg, .44), mix(bg, fg, .80), fg
    else:
        ansi_n = ["#c4223a", "#1f7a45", "#8a6a00", "#1f5fbf", "#8a3fc9", "#0f7a80"]
        ansi_b = ["#e0455b", "#2f9a5c", "#a88200", "#3a7ae0", "#a65ae6", "#1d9aa1"]
        c0, c8, c7, c15 = mix(fg, bg, .10), mix(fg, bg, .46), mix(bg, fg, .14), base
    tint = lambda hx: mix(parse(hx), accent, 0.12)
    ansi = [c0] + [tint(x) for x in ansi_n] + [c7, c8] + [tint(x) for x in ansi_b] + [c15]

    return {
        "dark": dark, "accent": accent, "on_accent": on_accent,
        "bg": bg, "base": base, "alt": alt, "surface": surface, "button": button,
        "border": border, "fg": fg, "dim": dim, "disabled": disabled, "link": link,
        "accent_dim": mix(accent, bg, .55), "warn": warn, "ok": ok, "ansi": ansi,
        "shade": (0, 0, 0),
    }


def write(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text)
    os.replace(tmp, path)


def write_kitty(p):
    H = lambda k: hexc(p[k])
    lines = [f"# {HEADER}",
             f"foreground {H('fg')}", f"background {H('bg')}",
             f"selection_foreground {H('on_accent')}", f"selection_background {H('accent')}",
             f"cursor {H('accent')}", f"cursor_text_color {H('bg')}", f"url_color {H('link')}",
             f"active_border_color {H('accent')}", f"inactive_border_color {H('border')}",
             f"bell_border_color {H('warn')}",
             f"active_tab_foreground {H('on_accent')}", f"active_tab_background {H('accent')}",
             f"inactive_tab_foreground {H('dim')}", f"inactive_tab_background {H('surface')}",
             f"tab_bar_background {H('bg')}",
             f"mark1_foreground {H('bg')}", f"mark1_background {H('accent')}",
             f"mark2_foreground {H('bg')}", f"mark2_background {hexc(p['ansi'][3])}",
             f"mark3_foreground {H('bg')}", f"mark3_background {hexc(p['ansi'][5])}"]
    lines += [f"color{i} {hexc(c)}" for i, c in enumerate(p["ansi"])]
    write(CFG / "kitty" / "current-theme.conf", "\n".join(lines) + "\n")
    subprocess.run(["pkill", "-USR1", "-x", "kitty"], stderr=subprocess.DEVNULL)


def write_fish(p):
    """Prompt colors (user / host / cwd) via universal vars, so open fish shells update live."""
    fish = shutil.which("fish")
    if not fish:
        return
    h = lambda c: hexc(c)[1:]
    vals = {
        "fish_color_user": h(p["accent"]),
        "fish_color_host": h(p["dim"]),
        "fish_color_cwd": h(mix(p["accent"], p["fg"], .35)),
    }
    cmd = "; ".join(f"set -U {k} {v}" for k, v in vals.items())
    subprocess.run([fish, "-c", cmd], stderr=subprocess.DEVNULL, timeout=5)


