def qt_scheme(p):
    A = lambda c, a=1.0: "#{:02x}{}".format(round(a * 255), hexc(c)[1:])
    button, fg = p["button"], p["fg"]
    step = 0.09 if p["dark"] else 0.05
    light = lambda c, d: hsl(*(lambda t: (t[0], t[1], t[2] + d))(to_hsl(c)))
    roles = [
        A(fg), A(button), A(light(button, step * 1.6)), A(light(button, step)), A(light(button, -0.12)),
        A(p["border"]), A(fg), A(WHITE if p["dark"] else BLACK), A(fg), A(p["base"]), A(p["bg"]),
        A(BLACK), A(p["accent"]), A(p["on_accent"]), A(p["link"]),
        A(mix(p["link"], p["ansi"][5], .5)), A(p["alt"]), A(BLACK), A(p["surface"]), A(fg), A(fg, .55),
    ]
    active = ", ".join(roles)
    dis = list(roles)
    for i in (0, 6, 8, 20):
        dis[i] = A(p["disabled"])
    dis[12] = A(p["border"])
    inactive = list(roles)
    inactive[12] = A(p["accent_dim"])
    return ("[ColorScheme]\nactive_colors=" + active + "\ndisabled_colors=" + ", ".join(dis) +
            "\ninactive_colors=" + ", ".join(inactive) + "\n")


def write_qt(p, use_kvantum):
    scheme = qt_scheme(p)
    for q in ("qt5ct", "qt6ct"):
        colors = CFG / q / "colors" / "glassveil.conf"
        write(colors, scheme)
        conf = CFG / q / f"{q}.conf"
        set_ini(conf, "Appearance", "color_scheme_path", str(colors))
        set_ini(conf, "Appearance", "custom_palette", "true")
        if use_kvantum:
            set_ini(conf, "Appearance", "style", "kvantum")


HEX_ANY = re.compile(r"#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b")
SVG_COLOR = re.compile(r"((?:fill|stroke|stop-color|flood-color|lighting-color|color)\s*[:=]\s*[\"']?)"
                       r"(#(?:[0-9a-fA-F]{6}|[0-9a-fA-F]{3}))\b")


def norm_hex(h):
    h = h.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    if len(h) == 8:
        return h[:2], parse(h[2:])
    return None, parse(h)


def find_kvantum_base(dark):
    for name in (KV_DARK if dark else KV_LIGHT):
        for root in KV_SEARCH:
            d = root / name
            kv, svg = d / f"{name}.kvconfig", d / f"{name}.svg"
            if kv.is_file() and svg.is_file():
                return name, kv, svg
    return None


def make_recolor(kv_text, svg_text, p, base_window):
    """Color mapper: saturated colors take the accent hue, neutrals take the palette tint."""
    counts = {}
    for m in HEX_ANY.finditer(kv_text):
        c = norm_hex(m.group(0))[1]
        counts[c] = counts.get(c, 0) + 1
    for m in SVG_COLOR.finditer(svg_text):
        c = norm_hex(m.group(2))[1]
        counts[c] = counts.get(c, 0) + 1

    def is_sat(c):
        h, s, l = to_hsl(c)
        return s >= 0.22 and 0.10 <= l <= 0.92

    sat = {c: n for c, n in counts.items() if is_sat(c)}
    ah, asat, al = to_hsl(p["accent"])
    dh, ds, dl = to_hsl(max(sat, key=lambda c: sat[c])) if sat else (ah, asat, al)
    ratio = asat / ds if ds > 0.01 else 1.0
    th, ts, tl = to_hsl(p["bg"])
    shift = tl - base_window

    def f(c):
        h, s, l = to_hsl(c)
        if is_sat(c):
            return hsl(ah, min(1.0, s * ratio), l + (al - dl))
        dist = l if p["dark"] else (1 - l)
        k = 1 - dist
        return hsl(th, min(ts, 0.25) * max(0.25, 1 - dist * 0.9), l + shift * k)
    return f


def kv_colors(p):
    H = lambda k: hexc(p[k])
    light = lambda c, d: hsl(*(lambda t: (t[0], t[1], t[2] + d))(to_hsl(c)))
    return {
        "window.color": H("bg"), "inactive.window.color": H("bg"), "base.color": H("base"),
        "alt.base.color": H("alt"), "button.color": H("button"),
        "light.color": hexc(light(p["button"], .09 if p["dark"] else .04)),
        "mid.light.color": hexc(light(p["button"], .05 if p["dark"] else .02)),
        "dark.color": hexc(light(p["button"], -.08 if p["dark"] else -.15)), "mid.color": H("border"),
        "highlight.color": H("accent"), "inactive.highlight.color": hexc(p["accent_dim"]),
        "text.color": H("fg"), "inactive.text.color": H("dim"), "window.text.color": H("fg"),
        "inactive.window.text.color": H("dim"), "button.text.color": H("fg"),
        "disabled.text.color": H("disabled"), "tooltip.base.color": H("surface"),
        "tooltip.text.color": H("fg"), "highlight.text.color": H("on_accent"),
        "link.color": H("link"), "link.visited.color": hexc(mix(p["link"], p["ansi"][5], .5)),
        "progress.indicator.text.color": H("on_accent"),
    }


def write_kvantum(p):
    found = find_kvantum_base(p["dark"])
    if not found:
        print("kvantum: no base theme found (install 'kvantum'), skipped", file=sys.stderr)
        return False
    name, kv_path, svg_path = found
    kv, svg = kv_path.read_text(), svg_path.read_text()

    m = re.search(r"^window\.color\s*=\s*(#[0-9a-fA-F]{6,8})", kv, re.M)
    base_window = to_hsl(norm_hex(m.group(1))[1])[2] if m else (0.17 if p["dark"] else 0.93)
    recolor = make_recolor(kv, svg, p, base_window)

    def rc_hex(hx):
        a, c = norm_hex(hx)
        out = hexc(recolor(c))
        return "#" + a + out[1:] if a else out

    svg = SVG_COLOR.sub(lambda m: m.group(1) + rc_hex(m.group(2)), svg)
    kv = HEX_ANY.sub(lambda m: rc_hex(m.group(0)), kv)

    colors = kv_colors(p)
    if "[GeneralColors]" in kv:
        def patch(section_match):
            body = section_match.group(2)
            for k, v in colors.items():
                if re.search(rf"^{re.escape(k)}\s*=", body, re.M):
                    body = re.sub(rf"^{re.escape(k)}\s*=.*$", f"{k}={v}", body, flags=re.M)
                else:
                    body += f"{k}={v}\n"
            return section_match.group(1) + body
        kv = re.sub(r"(\[GeneralColors\]\n)(.*?)(?=\n\[|\Z)", patch, kv, flags=re.S)
    else:
        kv += "\n[GeneralColors]\n" + "".join(f"{k}={v}\n" for k, v in colors.items())

    out = CFG / "Kvantum" / "Glassveil"
    write(out / "Glassveil.kvconfig", kv)
    write(out / "Glassveil.svg", svg)
    set_ini(CFG / "Kvantum" / "kvantum.kvconfig", "General", "theme", "Glassveil")
    print(f"kvantum: Glassveil generated from {name}")
    return True


def set_ini(path, section, key, value):
    path = Path(path)
    lines = path.read_text().splitlines() if path.exists() else []
    sec_re = re.compile(r"^\[(.+)\]\s*$")
    cur, sec_at, done = None, None, False
    for i, ln in enumerate(lines):
        m = sec_re.match(ln)
        if m:
            if cur == section and not done:
                lines.insert(i, f"{key}={value}")
                done = True
                break
            cur = m.group(1)
            if cur == section:
                sec_at = i
        elif cur == section and re.match(rf"^{re.escape(key)}\s*=", ln):
            lines[i] = f"{key}={value}"
            done = True
            break
    if not done:
        if sec_at is None:
            if lines and lines[-1].strip():
                lines.append("")
            lines.append(f"[{section}]")
        lines.insert((sec_at + 1) if sec_at is not None else len(lines), f"{key}={value}")
    write(path, "\n".join(lines) + "\n")


def sync(accent_hex, mode="dark"):
    mode = mode if mode in ("dark", "light") else "dark"
    p = make_palette(accent_hex, mode)
    steps = [("kitty", lambda: write_kitty(p)), ("fish", lambda: write_fish(p)), ("gtk", lambda: write_gtk(p))]
    kv_ok = False
    try:
        kv_ok = write_kvantum(p)
    except Exception as e:
        print(f"kvantum failed: {e}", file=sys.stderr)
    steps.append(("qt", lambda: write_qt(p, kv_ok)))
    for name, fn in steps:
        try:
            fn()
        except Exception as e:
            print(f"{name} failed: {e}", file=sys.stderr)
    return p


def main(argv):
    mode = os.environ.get("GLASSVEIL_THEME_MODE", "dark").lower()
    if "--mode" in argv:
        mode = argv[argv.index("--mode") + 1]
    accent = None
    if "--accent" in argv:
        accent = argv[argv.index("--accent") + 1]
    elif "--from-state" in argv:
        try:
            accent = json.loads(STATE.read_text()).get("accent")
        except Exception:
            accent = None
    if not accent or not re.fullmatch(r"#[0-9a-fA-F]{6}", accent):
        accent = DEFAULT_ACCENT
    sync(accent, mode)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
